// Generates src/data/hand-drawn.ts: the hero's sketches, as paths that take
// their colors from the theme. Run after changing a visual:
//   node scripts/draw-hand-visuals.mjs
//
// Follows the "Hand-drawn visuals" spec of the design system: canvases are 2x
// the reading size, and every visual has a fixed seed so a re-run draws the
// same wobble.
import { writeFileSync } from "node:fs";
import rough from "roughjs";

const STROKE = { text: "stroke-text", accent: "stroke-accent" };

const SHAPE = { roughness: 1.3, bowing: 1.2, strokeWidth: 4 };
const HATCH = {
  fillStyle: "hachure",
  hachureAngle: -45,
  hachureGap: 13,
  fillWeight: 3,
};

function sketchbook(seed) {
  const generator = rough.generator();
  const strokes = [];
  const add = (drawable) => {
    for (const { d, stroke, strokeWidth } of generator.toPaths(drawable)) {
      strokes.push({ d, width: strokeWidth, className: STROKE[stroke] });
    }
  };
  const options = (extra) => ({ ...SHAPE, seed, stroke: "text", ...extra });

  return {
    strokes,
    box: (x, y, w, h, extra) =>
      add(generator.rectangle(x, y, w, h, options(extra))),
    ellipse: (x, y, w, h, extra) =>
      add(generator.ellipse(x, y, w, h, options(extra))),
    /** Curved shaft with a two-stroke head, about 145° from the shaft */
    arrow(points, extra) {
      add(generator.curve(points, options(extra)));
      const [from, to] = points.slice(-2);
      const angle = Math.atan2(to[1] - from[1], to[0] - from[0]);
      for (const turn of [145, -145]) {
        const head = angle + (turn * Math.PI) / 180;
        add(
          generator.line(
            to[0],
            to[1],
            to[0] + 22 * Math.cos(head),
            to[1] + 22 * Math.sin(head),
            options(extra),
          ),
        );
      }
    },
  };
}

function heroHatch() {
  const page = sketchbook(11);
  page.ellipse(420, 420, 800, 800, {
    ...HATCH,
    stroke: "accent",
    fill: "accent",
    strokeWidth: 3,
    roughness: 0.9,
  });
  return { viewBox: "0 0 840 840", strokes: page.strokes };
}

function heroGround() {
  const page = sketchbook(5);
  page.box(8, 6, 824, 0.1, { stroke: "text", strokeWidth: 4, roughness: 1.6 });
  return { viewBox: "0 0 840 14", strokes: page.strokes };
}

function heroArrow() {
  const page = sketchbook(3);
  page.arrow(
    [
      [12, 12],
      [76, 22],
      [120, 80],
    ],
    { stroke: "accent", strokeWidth: 3.5 },
  );
  return { viewBox: "0 0 140 100", strokes: page.strokes };
}

const visuals = {
  HERO_HATCH: heroHatch(),
  HERO_ARROW: heroArrow(),
  HERO_GROUND: heroGround(),
};

const output = [
  "// Generated by scripts/draw-hand-visuals.mjs. Do not edit by hand.",
  "",
  "export interface HandVisual {",
  "  viewBox: string;",
  "  strokes: { d: string; width: number; className: string }[];",
  "}",
  "",
  ...Object.entries(visuals).map(
    ([name, visual]) =>
      `export const ${name}: HandVisual = ${JSON.stringify(visual, null, 2)};\n`,
  ),
].join("\n");

writeFileSync(new URL("../src/data/hand-drawn.ts", import.meta.url), output);
